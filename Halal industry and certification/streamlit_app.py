def ranked_table(summary: pd.DataFrame, group_column: str, label: str) -> pd.DataFrame:
    """Build a compact ranked table for a grouped summary."""
    out = summary[[group_column, "applications", "certification_rate", "median_processing_days"]].copy()
    out.insert(0, "Rank", range(1, len(out) + 1))
    out["Certified"] = out["certification_rate"].map(as_percentage)
    out["Median days"] = out["median_processing_days"].map(lambda v: f"{v:.0f}")
    out = out[
        ["Rank", group_column, "applications", "Certified", "Median days"]
    ].rename(
        columns={
            group_column: label,
            "applications": "Applications",
        }
    )
    return out


