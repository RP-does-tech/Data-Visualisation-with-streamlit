def find_csv() -> Path | None:
    """Return the first existing CSV path from the known locations."""
    return next((path for path in CSV_CANDIDATES if path.exists()), None)


@st.cache_data(show_spinner=False)
def load_data(path: str) -> pd.DataFrame:
    """Load the synthetic dataset and add analysis-ready columns."""
    df = pd.read_csv(path)

    for column in DATE_COLUMNS:
        if column in df.columns:
            df[column] = pd.to_datetime(df[column], errors="coerce")

    df["application_month"] = df["application_date"].dt.to_period("M").dt.to_timestamp()
    df["certified"] = df["certification_status"].eq("Certified")
    return df


def monthly_summary(df: pd.DataFrame, index: pd.DatetimeIndex) -> pd.DataFrame:
    """Aggregate applications by month on a continuous monthly index."""
    grouped = df.groupby("application_month").agg(
        applications=("application_id", "count"),
        certified=("certified", "sum"),
        avg_processing_days=("processing_time_days", "mean"),
    )
    out = grouped.reindex(index)
    out["applications"] = out["applications"].fillna(0).astype(int)
    out["certified"] = out["certified"].fillna(0).astype(int)
    out["certification_rate"] = out["certified"] / out["applications"].where(
        out["applications"] > 0
    )
    out["applications_3m_avg"] = out["applications"].rolling(3, min_periods=1).mean()
    return out.reset_index(names="application_month")


def group_summary(df: pd.DataFrame, column: str) -> pd.DataFrame:
    """Summarise volume, certification rate and processing time by category."""
    out = (
        df.groupby(column)
        .agg(
            applications=("application_id", "count"),
            certified=("certified", "sum"),
            certification_rate=("certified", "mean"),
            median_processing_days=("processing_time_days", "median"),
            avg_processing_days=("processing_time_days", "mean"),
        )
        .reset_index()
        .sort_values("applications", ascending=False)
    )
    out["certification_rate_pct"] = out["certification_rate"] * 100
    return out


def status_mix(df: pd.DataFrame, column: str) -> pd.DataFrame:
    """Count each status within each group and compute the within-group share."""
    out = (
        df.groupby([column, "certification_status"])
        .size()
        .reset_index(name="count")
    )
    totals = out.groupby(column)["count"].transform("sum")
    out["share"] = out["count"] / totals
    return out


def as_percentage(value: float) -> str:
    """Format a 0-1 rate as a percentage string."""
    return f"{value:.1%}"


